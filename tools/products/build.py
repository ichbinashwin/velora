def e(s):
    return html.escape(str(s), quote=True)


def prefix(lang):
    return "/" if lang == "en" else f"/{lang}/"


def page_url(lang):
    return f"{SITE}{prefix(lang)}products/"


def swatch_class(cid):
    return "sw-" + cid


def swatch_css():
    rules = []
    for cid, c in DATA["colours"].items():
        if c["hex"] == "assorted":
            rule = "background: conic-gradient(#2563eb 0 25%, #f4c430 0 50%, #e57fa6 0 75%, #2e8b57 0);"
        elif c.get("check"):
            rule = (f"background: linear-gradient(90deg, {c['hex']} 50%, transparent 50%) 0 0 / 8px 8px, "
                    f"linear-gradient({c['hex']} 50%, #fff 50%) 0 0 / 8px 8px;")
        else:
            rule = f"background: {c['hex']};"
        rules.append(f".{swatch_class(cid)} {{ {rule} }}")
    for ch in DATA["channels"]:
        rules.append(f".ch-{ch['id']} {{ --ch: #{ch['hex']}; }}")
    return "/* Generated by tools/products/build.py from catalog.json. Do not edit by hand. */\n" + "\n".join(rules) + "\n"


