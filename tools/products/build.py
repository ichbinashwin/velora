def safe_json(obj, **kwargs):
    """JSON that is safe inside a <script> element: no '</script>' or HTML comment break-out."""
    text = json.dumps(obj, ensure_ascii=False, **kwargs)
    return text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")

